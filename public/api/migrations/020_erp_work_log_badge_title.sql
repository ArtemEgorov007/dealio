-- Журнал работ: строки «Бирка» получают титул и объект работы.
--
-- Бирка на этом экране — обычный текст, каким её выдал каталог: у части
-- бирок вообще нет второй строки. Ширина в 512 символов — та же, что у
-- самой колонки badge: без второй строки титулом становится вся бирка
-- целиком, и обрезать его короче исходной строки было бы неверно.
ALTER TABLE erp_work_log
    ADD COLUMN title VARCHAR(512) NULL AFTER material,
    ADD COLUMN work_object VARCHAR(512) NULL AFTER title;
