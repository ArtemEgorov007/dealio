-- Уведомление автору заявки о смене статуса.
--
-- Статус заявки меняет тот, кто ведёт снабжение, — сегодня правкой в базе,
-- позже из функционала счетов. Отдельного экрана обработки заявок ещё нет,
-- поэтому источник события один: сам факт, что статус в строке отличается от
-- того, о котором автору уже сообщили.
ALTER TABLE erp_supply_requests
    ADD COLUMN notified_status VARCHAR(64) NULL AFTER status,
    ADD KEY erp_supply_requests_notified_idx (notified_status, status);

-- Уже импортированной истории статус проставляем как «сообщённый»: иначе
-- первый же прогон разошлёт уведомления по всем старым заявкам разом.
UPDATE erp_supply_requests SET notified_status = status;
