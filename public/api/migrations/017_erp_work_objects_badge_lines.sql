-- Бирка: строки остаются на своих местах.
--
-- Первая версия собирала бирку через CONCAT_WS, а он выбрасывает пустые части
-- вместе с их разделителями. У объекта без веса «Система покрытия» уезжала с
-- четвёртой строки на третью, и номер строки переставал что-либо значить:
-- разобрать такую бирку можно было только угадыванием, что в ней лежит.
--
-- Теперь разделители ставятся явно, а отсутствующая часть оставляет строку
-- пустой. В бирке всегда ровно четыре строки:
--
--     1. Титул
--     2. Объект работы
--     3. Вес: <вес> <цвет>
--     4. Система покрытия
--
-- Висящего «Вес:» при этом не появляется: без веса третья строка несёт только
-- цвет, а без обоих остаётся пустой. Печатать ярлык без значения незачем, а
-- разбору по номеру строки пустая строка не мешает.
--
-- Меняем отдельной миграцией, а не правкой 016: та уже применена, и повторно
-- её никто не выполнит — исправление на месте разошлось бы с базами, где
-- таблица уже создана. Вычисляемая колонка пересчитывается при ALTER, поэтому
-- уже заведённые бирки приводятся к новому виду сами.
ALTER TABLE erp_work_objects
    MODIFY COLUMN badge VARCHAR(512)
    GENERATED ALWAYS AS (
        CONCAT(
            title, '\n',
            work_object, '\n',
            CASE
                WHEN weight IS NULL THEN ''
                ELSE CONCAT(
                    'Вес: ',
                    -- Вес по-русски: запятая и без хвостовых нулей. DECIMAL дал
                    -- бы «1.570» там, где на существующих бирках стоит «1,57».
                    REPLACE(
                        TRIM(TRAILING '.' FROM TRIM(TRAILING '0' FROM weight)),
                        '.',
                        ','
                    )
                )
            END,
            CASE
                WHEN color = '' THEN ''
                -- Без веса цвет остаётся один на строке, без ведущего пробела.
                WHEN weight IS NULL THEN color
                ELSE CONCAT(' ', color)
            END,
            '\n',
            -- Прочерк — это «параметра нет», печатать его на бирке незачем.
            CASE WHEN coating_system IN ('', '-') THEN '' ELSE coating_system END
        )
    ) STORED;
