-- Рабочая номенклатура: справочник объектов выполнения работ.
--
-- Объект выполнения работ — то, над чем физически ведётся работа. Сегодня это
-- отдельная металлоконструкция под огнезащитное покрытие, завтра — монтируемый
-- элемент лесов, участок корабля под окраску, монтажное соединение. Поэтому
-- таблица описывает объект нейтрально: «титул» и «объект работы» вместо
-- «титул» и «марка», как эти же поля называются в чертежах и в старых листах.
--
-- Процесс внесения данных появится позже: сейчас заводится только хранилище и
-- его связи. Права раздел пока не требует — отношения с сотрудниками, кроме
-- авторства записи, у него нет.
CREATE TABLE IF NOT EXISTS erp_work_objects (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Договор, по которому выполняется работа. Ссылаемся на внутренний номер,
    -- а не на суррогатный id: им договор называют в разговоре, по нему же
    -- сцеплены расценки, и он уже уникален в erp_contracts.
    contract_internal_number VARCHAR(64) NOT NULL,

    platform VARCHAR(255) NOT NULL DEFAULT '',

    -- Титул и объект работы короче остальных текстовых полей намеренно: они
    -- вчетвером образуют уникальный ключ, а InnoDB даёт на ключ 3072 байта,
    -- то есть 768 символов в utf8mb4. Это короткие обозначения вроде
    -- «Титул 42» и «Б-1», 128 символов им с запасом хватает, зато ключ можно
    -- держать полным — без префикса, который склеивал бы разные значения с
    -- одинаковым началом и отвергал их как дубли.
    title VARCHAR(128) NOT NULL,

    -- «Объект работы» — это то, что в чертежах и на старых листах зовётся
    -- маркой. Имя колонки нейтральное, потому что физическое воплощение
    -- меняется от договора к договору, а роль поля — нет.
    work_object VARCHAR(128) NOT NULL,

    -- Индекс — сцепка титула и объекта работы. Колонка вычисляемая, а не
    -- заполняемая руками: сцепка, которую можно ввести отдельно от своих
    -- частей, рано или поздно с ними разойдётся. То же самое поле в листе
    -- «Логисты» называется «Титул и марка».
    index_code VARCHAR(512)
        GENERATED ALWAYS AS (CONCAT(title, '-', work_object)) STORED,

    project_name VARCHAR(512) NOT NULL DEFAULT '',

    -- Площадь в м2 и вес в тоннах: по ним считаются обе цены расценки
    -- (price_m2 и price_ton в erp_contract_rates).
    area DECIMAL(12,3) NULL,
    weight DECIMAL(12,3) NULL,

    -- Четыре параметра, по которым объекту подбирается расценка договора:
    -- сюда ложатся param1..param4 из erp_contract_rates. Первые два уже имеют
    -- устоявшийся смысл и названы прямо, третий и четвёртый договор назовёт
    -- сам — как и в самой таблице расценок, где все четыре свободные.
    --
    -- Прочерк по умолчанию — не украшение, а та же договорённость, что и в
    -- расценках (015_erp_contract_rates_defaults.sql): пустая строка совпала
    -- бы с любой другой пустой, то есть с чужой расценкой, а прочерк говорит
    -- «здесь параметра нет» явно. Обе стороны подбора обязаны понимать «нет
    -- значения» одинаково, иначе объект молча склеится не с той ценой.
    -- Слой внесения данных нормализует ввод тем же erp_contract_param().
    --
    -- Система покрытия и цвет уже́ остальных: вместе с титулом и объектом
    -- работы они складываются в бирку, а её принимает erp_work_log.badge
    -- шириной 512. При таких размерах самая длинная возможная бирка — 470
    -- символов, то есть не влезть в журнал она не может в принципе.
    coating_system VARCHAR(128) NOT NULL DEFAULT '-',
    coating_thickness VARCHAR(255) NOT NULL DEFAULT '-',
    param3 VARCHAR(255) NOT NULL DEFAULT '-',
    param4 VARCHAR(255) NOT NULL DEFAULT '-',

    -- Цвет в подборе расценки не участвует, поэтому и прочерк ему не нужен:
    -- он только печатается в бирке, а печатать «-» незачем.
    color VARCHAR(64) NOT NULL DEFAULT '',

    -- Бирка — тоже сцепка, и тоже вычисляемая. Её печатают и сканируют, по её
    -- тексту работа находится в журнале, поэтому разойтись со своими частями
    -- она не имеет права.
    --
    -- Вес в бирке пишется по-русски: запятая вместо точки и без хвостовых
    -- нулей, иначе DECIMAL дал бы «1.570» там, где на существующих бирках
    -- стоит «1,57», и тексты перестали бы совпадать. Пустой вес не оставляет
    -- висящего «Вес:» — строка целиком выпадает из бирки.
    badge VARCHAR(512)
        GENERATED ALWAYS AS (
            CONCAT_WS(
                '\n',
                title,
                work_object,
                CASE
                    WHEN weight IS NULL THEN NULL
                    ELSE CONCAT(
                        'Вес: ',
                        REPLACE(
                            TRIM(TRAILING '.' FROM TRIM(TRAILING '0' FROM weight)),
                            '.',
                            ','
                        ),
                        CASE WHEN color = '' THEN '' ELSE CONCAT(' ', color) END
                    )
                END,
                -- Прочерк — это «параметра нет», и печатать его на бирке
                -- незачем: строка просто выпадает, как и при пустом значении.
                NULLIF(NULLIF(coating_system, ''), '-')
            )
        ) STORED,

    -- Автор записи. Ссылка нужна для связи с сотрудником, а ФИО хранится
    -- рядом снимком: запись должна пережить увольнение автора и остаться с
    -- именем того, кто её внёс, а не опустеть по ON DELETE SET NULL.
    created_by BIGINT UNSIGNED NULL,
    author_fio VARCHAR(255) NOT NULL DEFAULT '',

    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),

    PRIMARY KEY (id),

    -- Один объект на титул в пределах договора и площадки. Справочник без
    -- этого правила молча набирает дубли, а по дублю невозможно сказать,
    -- какую из двух строк описывает отсканированная бирка. Площадка входит в
    -- ключ намеренно: один и тот же чертёж изготавливают на двух площадках.
    UNIQUE KEY erp_work_objects_index_unique
        (contract_internal_number, platform, title, work_object),

    KEY erp_work_objects_contract_idx (contract_internal_number),
    KEY erp_work_objects_title_idx (title),
    KEY erp_work_objects_badge_idx (badge(191)),
    KEY erp_work_objects_index_code_idx (index_code(191)),

    CONSTRAINT erp_work_objects_contract_fk
        FOREIGN KEY (contract_internal_number) REFERENCES erp_contracts (internal_number)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT erp_work_objects_author_fk
        FOREIGN KEY (created_by) REFERENCES erp_users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
